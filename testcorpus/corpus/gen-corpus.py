#!/usr/bin/env python3
"""Generate a corpus of known arithmetic/bitwise functions for the SP6
mutation-engine benchmark (WP12).

Emits N functions `f000`, `f001`, ... each a well-defined *unsigned* expression
over params `a`, `b`, `c` at a declared width (32 or 64). Two artifacts:

  gen_manifest.json  - { "fNNN": {"expr": str, "params": [...], "width": int}, ... }
                       the clean-side ground truth: each function's exact source
                       expression. Consumed by gen-oracle.py.
  gen_corpus.c       - compilable C (one exported function per entry), the input
                       to build-gen.ps1 (compile + VMProtect mutation protect).

Only well-defined unsigned operators are emitted: + - * & | ^ ~ << >>. Shift
amounts are always in [0, width) (constant, or a param masked to width-1), so
there is no C undefined behaviour and the oracle can model exact wraparound.

Usage:  python gen-corpus.py [N] [--seed S] [--max-depth D] [--out DIR]
Deterministic for a given (N, seed): regenerating reproduces the same corpus.
"""
import argparse
import json
import os
import random

PARAM_NAMES = ["a", "b", "c"]
WIDTHS = [32, 64]

# (symbol, is_commutative-ish) — purely for generation variety.
BINOPS = ["+", "-", "*", "&", "|", "^"]


def gen_expr(rng, params, width, depth):
    """Build a random well-defined unsigned expression string over `params`."""
    mask_bits = width - 1  # shift-amount mask (width is a power of two)

    def leaf():
        if rng.random() < 0.65:
            return rng.choice(params)
        # small literal constant (kept well within the width)
        return str(rng.choice([0, 1, 2, 3, 5, 7, 0xFF, 0xFFFF, 0x7FFFFFFF]))

    def build(d):
        if d <= 0 or rng.random() < 0.25:
            return leaf()
        r = rng.random()
        if r < 0.15:
            # unary bitwise NOT
            return "(~" + build(d - 1) + ")"
        if r < 0.40:
            # shift by a safe amount: constant in [0,width) or a masked param
            sub = build(d - 1)
            op = rng.choice(["<<", ">>"])
            if rng.random() < 0.6:
                amt = str(rng.randint(0, width - 1))
            else:
                amt = "(" + rng.choice(params) + " & " + str(mask_bits) + ")"
            return "(" + sub + " " + op + " " + amt + ")"
        # binary op
        op = rng.choice(BINOPS)
        return "(" + build(d - 1) + " " + op + " " + build(d - 1) + ")"

    e = build(depth)
    if e in params or e.lstrip("-").isdigit():
        # ensure at least one operation so the function is non-trivial
        e = "(" + e + " + " + rng.choice(params) + ")"
    return e


def ctype(width):
    return "uint%d_t" % width


def c_render(expr, width):
    """Render a manifest expr into C that computes at width-W *unsigned*
    throughout. C integer literals default to signed `int`, so a pure-literal
    subexpression (e.g. `255 | 0`) or a constant shift >= 32 would otherwise be
    evaluated at 32-bit signed in the native code and diverge from the width-W
    oracle. Suffixing every literal (`u` = unsigned int / 32-bit, `ull` =
    unsigned long long / 64-bit) pins every operation to width-W unsigned, so
    the compiled function's behaviour equals the oracle exactly."""
    suffix = "u" if width == 32 else "ull"
    out = []
    i, n = 0, len(expr)
    while i < n:
        c = expr[i]
        if c.isdigit():
            j = i
            if expr[i] == "0" and i + 1 < n and expr[i + 1] in "xX":
                j = i + 2
                while j < n and expr[j] in "0123456789abcdefABCDEF":
                    j += 1
            else:
                while j < n and expr[j].isdigit():
                    j += 1
            out.append(expr[i:j] + suffix)
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def emit_c(manifest):
    lines = [
        "/* Auto-generated by gen-corpus.py — SP6 mutation benchmark corpus. */",
        "/* Each function is a well-defined unsigned expression; gen_manifest.json",
        "   carries the same expressions as the clean-side ground truth. */",
        "#include <stdint.h>",
        "",
        "#if defined(_WIN32)",
        "#define VMPX_EXPORT __declspec(dllexport)",
        "#else",
        "#define VMPX_EXPORT",
        "#endif",
        "",
    ]
    for name in sorted(manifest):
        e = manifest[name]
        ct = ctype(e["width"])
        args = ", ".join("%s %s" % (ct, p) for p in e["params"])
        lines.append("VMPX_EXPORT %s %s(%s) {" % (ct, name, args))
        lines.append("    return (%s)(%s);" % (ct, c_render(e["expr"], e["width"])))
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("n", nargs="?", type=int, default=100,
                    help="number of functions to generate")
    ap.add_argument("--seed", type=int, default=1234567,
                    help="RNG seed (deterministic corpus)")
    ap.add_argument("--max-depth", type=int, default=4,
                    help="max expression tree depth")
    ap.add_argument("--out", default=os.path.dirname(os.path.abspath(__file__)),
                    help="output directory")
    args = ap.parse_args()

    rng = random.Random(args.seed)
    manifest = {}
    for i in range(args.n):
        name = "f%03d" % i
        width = rng.choice(WIDTHS)
        nparams = rng.randint(1, 3)
        params = PARAM_NAMES[:nparams]
        expr = gen_expr(rng, params, width, args.max_depth)
        manifest[name] = {"expr": expr, "params": params, "width": width}

    os.makedirs(args.out, exist_ok=True)
    mpath = os.path.join(args.out, "gen_manifest.json")
    with open(mpath, "w") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
    cpath = os.path.join(args.out, "gen_corpus.c")
    with open(cpath, "w") as f:
        f.write(emit_c(manifest))

    print("generated %d functions (seed=%d)" % (args.n, args.seed))
    print("  manifest: %s" % mpath)
    print("  source:   %s" % cpath)


if __name__ == "__main__":
    main()
